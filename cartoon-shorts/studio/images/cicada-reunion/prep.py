# prep.py - split sheets, trim, normalise the guy colours, measure anchors -> public/cicada-reunion + src/cicada-reunion/sprites.ts
import json, os
import numpy as np, cv2
from PIL import Image
OUT = '../../public/cicada-reunion'
os.makedirs(OUT, exist_ok=True); os.makedirs('qa', exist_ok=True)
exec(open('prep_lib.py').read())
info = {}
def despill_mag(a):
    r, g, b = [a[..., i].astype(int) for i in range(3)]
    a[(r > g + 90) & (b > g + 90), 3] = 0
    return a
def save(name, a, guy=True, mag=False):
    a = despill_mag(a) if mag else despill(a)
    a = drop_specks(a)
    if guy:
        a = normalise(a); a, _ = fix_outline(a)
    a, off = trim(a, 12)
    Image.fromarray(a, 'RGBA').save(f'{OUT}/{name}.png', optimize=True)
    d = dict(w=a.shape[1], h=a.shape[0], feet=feet(a), **box(a))
    if guy: d['hd'] = head_disc(a)
    info[name] = d; print(name, d['w'], d['h'])
for n, s in zip(['listen', 'ears', 'shrug'], split_n(load('guy'), 3)): save(n, s, mag=True)
for n, s in zip(['nymph', 'adult', 'sing'], split_n(load('bugs'), 3)): save(n, s, guy=False, mag=True)
for n, s in zip(['mower', 'cal', 'hat'], split_n(load('props'), 3)): save(n, s, guy=False)
for p in ['under', 'tree']:
    pl = Image.open(f'raw/{p}.png').convert('RGB'); pl.save(f'{OUT}/{p}.jpg', quality=92); info[p] = dict(w=pl.width, h=pl.height)
json.dump(info, open('sprites.json', 'w'), indent=1)
with open('../../src/cicada-reunion/sprites.ts', 'w') as f:
    f.write('// generated by images/cicada-reunion/prep.py\nexport const SPR = ' + json.dumps(info) + ' as const;\n')
names = [k for k in info if k not in ('under', 'tree')]
W = 360; sheet = Image.new('RGB', (W * 5, W * 2), (255, 0, 255))
for i, n in enumerate(names):
    im = Image.open(f'{OUT}/{n}.png'); im.thumbnail((W - 10, W - 10))
    bg = Image.new('RGB', (W, W), (255, 0, 255) if i % 2 else (20, 30, 90)); bg.paste(im, (5, 5), im); sheet.paste(bg, ((i % 5) * W, (i // 5) * W))
sheet.save('qa/sheet.png')
