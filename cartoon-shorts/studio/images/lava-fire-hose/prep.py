# prep.py - trim, normalise colours, measure head/feet/nozzle -> public/lava-fire-hose + src/lava-fire-hose/sprites.ts
import json, os
import numpy as np, cv2
from PIL import Image

OUT = '../../public/lava-fire-hose'
os.makedirs(OUT, exist_ok=True)
PAL = np.array([[254, 253, 253], [237, 235, 235], [252, 141, 144]], float)  # channel palette (memory/STYLE.md)

def load(n): return np.asarray(Image.open(f'keyed/{n}.png').convert('RGBA')).copy()

def split(a):
    al = a[..., 3]; h, w = al.shape
    empty = (al > 10).sum(0) == 0
    runs = []; x = 0
    while x < w:
        if empty[x]:
            s = x
            while x < w and empty[x]: x += 1
            runs.append((s, x))
        else: x += 1
    runs = [r for r in runs if r[0] > 0 and r[1] < w]
    s, e = max(runs, key=lambda r: r[1] - r[0]); c = (s + e) // 2
    return a[:, :c], a[:, c:]

def trim(a, pad=12):
    ys, xs = np.where(a[..., 3] > 10)
    y0, y1, x0, x1 = max(ys.min() - pad, 0), min(ys.max() + pad + 1, a.shape[0]), max(xs.min() - pad, 0), min(xs.max() + pad + 1, a.shape[1])
    return a[y0:y1, x0:x1].copy()

def normalise(a):
    rgb = a[..., :3].astype(float); op = a[..., 3] == 255
    D = np.stack([np.sqrt(((rgb - c) ** 2).sum(2)) for c in PAL])   # nearest palette colour wins
    k = D.argmin(0); dm = D.min(0)
    for i, c in enumerate(PAL):
        m = op & (dm < 40) & (k == i); rgb[m] = c
    d = np.sqrt((rgb ** 2).sum(2)); rgb[op & (d < 25)] = 0
    a[..., :3] = rgb.astype(np.uint8); return a

def head_feet(a):
    al = a[..., 3]; h, w = al.shape
    white = ((a[..., :3].astype(int).sum(2) > 600) & (al > 128)).astype(np.uint8)
    ff = white.copy(); cv2.floodFill(ff, np.zeros((h + 2, w + 2), np.uint8), (0, 0), 2)
    solid = np.where(ff == 2, 0, 1).astype(np.uint8)
    dt = cv2.distanceTransform(solid, cv2.DIST_L2, 5)
    hy, hx = np.unravel_index(dt.argmax(), dt.shape)
    ys, xs = np.where(al > 128); yb = ys.max(); band = ys > yb - 0.06 * (yb - ys.min())
    return dict(head=[int(hx), int(hy), float(dt[hy, hx])], feet=[float((xs[band].min() + xs[band].max()) / 2), int(yb)])

def brass(a):
    r, g, b = [a[..., i].astype(int) for i in range(3)]
    m = (a[..., 3] > 200) & (r > 120) & (g > 80) & (b < 110) & (r - b > 70)
    ys, xs = np.where(m)
    return ys, xs

info = {}
def save(name, a, char=True, extra=None):
    if char: a = normalise(a)
    a = trim(a)
    Image.fromarray(a, 'RGBA').save(f'{OUT}/{name}.png', optimize=True)
    d = dict(w=a.shape[1], h=a.shape[0])
    if char: d.update(head_feet(a))
    if extra: d.update(extra(a))
    info[name] = d

def nozzle_side(a):
    ys, xs = brass(a)
    tipx = int(xs.max()); ty = float(ys[xs > tipx - 25].mean())
    near = np.abs(ys - ty) < 120; xs, ys = xs[near], ys[near]
    return dict(tip=[tipx, ty], back=[int(xs.min()), float(ys[xs < xs.min() + 25].mean())])

def nozzle_up(a):
    ys, xs = brass(a)
    top = int(ys.min()); row = xs[ys < top + 25]; bot = int(ys.max())
    return dict(tip=[float(row.mean()), top], back=[float(xs[ys > bot - 25].mean()), bot])

save('hero_aim', load('hero_aim'), extra=nozzle_side)
save('worried_aim', load('worried_aim'), extra=nozzle_side)
save('deadpan_nozzle', load('deadpan_nozzle'), extra=nozzle_up)
for n in ['cheer', 'yawn', 'proud']: save(n, load(n))
# close-up: head only (body cut by the picture edge)
save('shock_cu', load('shock_cu'))

def muzzle(a):
    al = a[..., 3] > 128; ys, xs = np.where(al)
    k = (xs - ys).argmax(); return dict(muzzle=[int(xs[k]), int(ys[k])], keel=int(ys.max()))
save('ship', load('ship'), char=False, extra=muzzle)
save('house', load('house'), char=False)
L, R = split(load('boats'))
save('boat_blue', L, char=False); save('boat_orange', R, char=False)
for n in ['bg_field', 'bg_harbor']:
    b = Image.open(f'raw/{n}.png').convert('RGB'); b.save(f'{OUT}/{n}.png', optimize=True); info[n] = dict(w=b.width, h=b.height)
os.makedirs('../../src/lava-fire-hose', exist_ok=True)
with open('../../src/lava-fire-hose/sprites.ts', 'w') as f:
    f.write('// generated by images/lava-fire-hose/prep.py\nexport const SPR = ' + json.dumps(info) + ' as const;\n')
for k, v in info.items(): print(k, v)
