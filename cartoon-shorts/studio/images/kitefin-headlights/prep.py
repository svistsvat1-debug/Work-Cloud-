# ---- photophore dots for the code glow: points inside the lower body of each shark sprite ----
import random
random.seed(4)
for n in ['sh_calm', 'sh_sneak', 'sh_huh']:
    a = np.asarray(Image.open(f'{OUT}/{n}.png').convert('RGBA'))
    h, w = a.shape[:2]
    op = a[..., 3] == 255
    rgb = a[..., :3].astype(int)
    brown = op & (rgb.sum(2) > 150) & (rgb.sum(2) < 420)
    dots = []
    tries = 0
    while len(dots) < 46 and tries < 20000:
        tries += 1
        x = random.randint(int(0.12 * w), int(0.82 * w)); y = random.randint(int(0.35 * h), int(0.85 * h))
        col = brown[:, x]; ys = np.where(col)[0]
        if len(ys) == 0: continue
        if y < ys.min() + 0.5 * (ys.max() - ys.min()): continue
        if not brown[y - 3:y + 4, x - 3:x + 4].all(): continue
        if any((x - d[0]) ** 2 + (y - d[1]) ** 2 < 22 ** 2 for d in dots): continue
        dots.append([x, y])
    info[n]['dots'] = dots
    print(n, 'dots', len(dots))
json.dump(info, open('sprites.json', 'w'), indent=1)
