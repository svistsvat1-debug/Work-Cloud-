import json, os
import numpy as np, cv2
from PIL import Image, ImageDraw
OUT = '../../public/kitefin-headlights'
os.makedirs(OUT, exist_ok=True)
exec(open('prep_lib.py').read())   # load, despill, trim, normalise, feet, head_disc, box, split_n, drop_specks, fix_outline
info = {}

def despill_any(a):
    """greenish OR magenta-ish leftovers of the key -> transparent (the pigeon's teal / violet neck is safe: checked)"""
    r, g, b = [a[..., i].astype(int) for i in range(3)]
    a[(g > r + 60) & (g > b + 60), 3] = 0
    a[(r > g + 90) & (b > g + 90), 3] = 0
    return a

def eyes_white(a):
    """big white cartoon eyes of the pigeon: white blobs (>= 600 px) -> list of [cx, cy, r] sorted by size"""
    w = ((a[..., :3].astype(int).min(2) > 225) & (a[..., 3] > 200)).astype(np.uint8)
    n, lab, st, cen = cv2.connectedComponentsWithStats(w, connectivity=4)
    out = [[float(cen[i][0]), float(cen[i][1]), float(np.sqrt(st[i, cv2.CC_STAT_AREA] / np.pi))] for i in range(1, n) if st[i, cv2.CC_STAT_AREA] >= 300]
    out.sort(key=lambda e: -e[2])
    return out

def save(name, a, guy=True, pre=1.0, pad=12):
    a = despill_any(a)
    a = drop_specks(a)
    if guy:
        a = normalise(a)
        a, nfix = fix_outline(a)
        if nfix: print('   outline fixed', name, nfix, 'px')
    a, off = trim(a, pad)
    im = Image.fromarray(a, 'RGBA')
    if pre != 1.0:
        im = im.resize((round(a.shape[1] * pre), round(a.shape[0] * pre)), Image.LANCZOS)
    im.save(f'{OUT}/{name}.png', optimize=True)
    d = dict(w=a.shape[1], h=a.shape[0], feet=feet(a), **box(a))
    if guy: d['hd'] = head_disc(a)
    else: d['eyes'] = eyes_white(a)[:2]
    info[name] = d
    print(name, a.shape[1], a.shape[0], 'hd' if guy else 'eyes', [round(v) for v in (d['hd'] if guy else (d['eyes'][0] if d['eyes'] else [0, 0, 0]))])
    Image.fromarray(a, 'RGBA').save(f'qa/spr_{name}.png')
    return a

def extreme(a, fn, mask=None):
    al = a[..., 3] > 128
    if mask is not None: al &= mask
    ys, xs = np.where(al); i = np.argmax(fn(xs, ys)); return [int(xs[i]), int(ys[i])]

def grid(name):
    """measuring sheet: the sprite on light grey with a 50 px grid (numbers every 100 px)"""
    a = Image.open(f'qa/spr_{name}.png'); w, h = a.size
    bg = Image.new('RGBA', (w, h), (215, 215, 215, 255)); bg.alpha_composite(a); d = ImageDraw.Draw(bg)
    for x in range(0, w, 50): d.line([(x, 0), (x, h)], fill=(255, 0, 0, 255) if x % 100 == 0 else (255, 160, 160, 255), width=1)
    for y in range(0, h, 50): d.line([(0, y), (w, y)], fill=(0, 0, 255, 255) if y % 100 == 0 else (160, 160, 255, 255), width=1)
    for x in range(0, w, 100): d.text((x + 2, 2), str(x), fill='red')
    for y in range(0, h, 100): d.text((2, y + 2), str(y), fill='blue')
    bg.convert('RGB').save(f'qa/measure_{name}.jpg', quality=85)

