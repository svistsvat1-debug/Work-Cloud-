# ---- background plate: pad below by repeating the bottom window band, mirror-pad the sides ----
pl = np.asarray(Image.open('raw/plate.png').convert('RGB')).copy()
H, W = pl.shape[:2]
# vertical period of the window rows in the bottom 500 px (autocorrelation of the row means)
rows = pl[H - 520:H - 20].astype(float).mean(axis=(1, 2)); rows -= rows.mean()
ac = np.correlate(rows, rows, 'full')[len(rows) - 1:]; per = int(np.argmax(ac[40:200]) + 40)
band = pl[H - 20 - 2 * per:H - 20]
ext = np.concatenate([pl[:H - 20]] + [band] * 6, 0)
ext = cv2.copyMakeBorder(ext, 0, 0, 512, 512, cv2.BORDER_REFLECT_101)
Image.fromarray(ext).save(f'{OUT}/plate.jpg', quality=92)
info['plate'] = dict(w=int(ext.shape[1]), h=int(ext.shape[0]), padX=512, srcW=W, srcH=H, period=per)
print('plate', ext.shape, 'window period', per)

json.dump(info, open('sprites.json', 'w'), indent=1)
os.makedirs('../../src/pigeon-landing', exist_ok=True)
with open('../../src/pigeon-landing/sprites.ts', 'w') as f:
    f.write('// generated by images/pigeon-landing/prep.py - native sizes and anchors (px of the trimmed sprite)\n')
    f.write('export const SPR = ' + json.dumps(info) + ' as const;\n')
