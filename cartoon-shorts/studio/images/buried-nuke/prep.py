# ---- the farm plate: surface line + band boundaries (at several x) ----
b = np.asarray(Image.open('raw/farm.png').convert('RGB')).astype(int)
Hh, Ww = b.shape[:2]
Image.fromarray(b.astype(np.uint8)).save(f'{OUT}/farm.png', optimize=True)
dark = b.sum(2) < 120
def first_dark(x, y0, y1):
    col = dark[y0:y1, x]; return int(np.argmax(col) + y0) if col.any() else None
surf = int(np.median([first_dark(x, 560, 700) for x in range(200, 900, 25)]))
# band boundaries: black wavy lines below the surface (scan the centre column)
lines = []
for x in range(150, 950, 50):
    col = dark[surf + 40:, x]; ys = np.where(col)[0] + surf + 40
    runs = []
    for y in ys:
        if not runs or y > runs[-1][1] + 3: runs.append([y, y])
        else: runs[-1][1] = y
    lines.append([r[0] for r in runs if r[1] - r[0] < 14])
print('surface', surf, 'lines sample', lines[:3])
cols = {k: [int(v) for v in b[int(f * Hh), Ww // 2]] for k, f in [('sky', 0.1), ('top', 0.44), ('clay', 0.55), ('wet', 0.70), ('deep', 0.95)]}
info['farm'] = dict(w=Ww, h=Hh, surface=surf, cols=cols)
