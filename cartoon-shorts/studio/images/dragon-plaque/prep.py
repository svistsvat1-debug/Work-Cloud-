# prep.py - split the sheets, trim, normalise the guy's colours, measure anchors
# -> public/dragon-plaque/*.png + lab.jpg + ground.jpg + src/dragon-plaque/sprites.ts   (run from images/dragon-plaque)
import json, os
import numpy as np, cv2
from PIL import Image
OUT = '../../public/dragon-plaque'
os.makedirs(OUT, exist_ok=True)
exec(open('prep_lib.py').read())
info = {}
def despill_mag(a):
    r, g, b = [a[..., i].astype(int) for i in range(3)]
    a[(r > g + 90) & (b > g + 90), 3] = 0
    return a
def save(name, a, guy=True, pad=12, mag=False):
    a = despill_mag(a) if mag else despill(a)
    a = drop_specks(a)
    if guy:
        a = normalise(a); a, nfix = fix_outline(a)
        if nfix: print('   outline fixed', name, nfix, 'px')
    a, off = trim(a, pad)
    Image.fromarray(a, 'RGBA').save(f'{OUT}/{name}.png', optimize=True)
    d = dict(w=a.shape[1], h=a.shape[0], feet=feet(a), **box(a))
    if guy: d['hd'] = head_disc(a)
    info[name] = d
    print(name, a.shape[1], a.shape[0], [round(v) for v in d['hd']] if guy else '')
    Image.fromarray(a, 'RGBA').save(f'qa/spr_{name}.png')
    return a
def extreme(a, fn):
    ys, xs = np.where(a[..., 3] > 128); i = np.argmax(fn(xs, ys)); return [int(xs[i]), int(ys[i])]
def colour_blobs(a, rgb, tol=60, min_area=200):
    m = ((np.abs(a[..., :3].astype(int) - np.array(rgb)).sum(2) < tol) & (a[..., 3] > 200)).astype(np.uint8)
    n, lab, st, cen = cv2.connectedComponentsWithStats(m, connectivity=8)
    out = [[float(cen[i][0]), float(cen[i][1]), int(st[i][2]), int(st[i][3]), int(st[i][4])] for i in range(1, n) if st[i][4] >= min_area]
    return sorted(out, key=lambda b: -b[4])
for n, s in zip(['present', 'drill', 'shock'], split_n(load('guyA'), 3)): save(n, s)
info['present']['hand'] = extreme(np.asarray(Image.open(f'{OUT}/present.png')), lambda x, y: x)
info['drill']['tip'] = extreme(np.asarray(Image.open(f'{OUT}/drill.png')), lambda x, y: x)
for n, s in zip(['scrape', 'tube', 'cheer'], split_n(load('guyB'), 3)): save(n, s)
info['scrape']['tip'] = extreme(np.asarray(Image.open(f'{OUT}/scrape.png')), lambda x, y: x)
info['tube']['top'] = extreme(np.asarray(Image.open(f'{OUT}/tube.png')), lambda x, y: -y)
sk = save('skull', load('skull'), guy=False, mag=True)
info['skull']['sockets'] = colour_blobs(sk, [59, 42, 30], 90, 800)[:3]
info['skull']['cream'] = colour_blobs(sk, [242, 230, 200], 60, 100)[:6]
print('skull', info['skull']['sockets'], info['skull']['cream'])
for n, s in zip(['tooth', 'bucket', 'finger'], split_n(load('props'), 3)): save(n, s, guy=False, mag=True)
save('denisovan', load('denisovan'), guy=False)
info['denisovan']['hd'] = head_disc(np.asarray(Image.open(f'{OUT}/denisovan.png')))
for n in ['lab', 'ground']:
    pl = np.asarray(Image.open(f'raw/{n}.png').convert('RGB')).copy(); H, W = pl.shape[:2]
    ext = cv2.copyMakeBorder(pl, 200, 200, 512, 512, cv2.BORDER_REFLECT_101)
    Image.fromarray(ext).save(f'{OUT}/{n}.jpg', quality=92)
    info[n] = dict(w=int(ext.shape[1]), h=int(ext.shape[0]), padX=512, padTop=200, srcW=W, srcH=H)
json.dump(info, open('sprites.json', 'w'), indent=1)
os.makedirs('../../src/dragon-plaque', exist_ok=True)
with open('../../src/dragon-plaque/sprites.ts', 'w') as f:
    f.write('// generated by images/dragon-plaque/prep.py - native sizes and anchors (px of the trimmed sprite)\n')
    f.write('export const SPR = ' + json.dumps(info) + ' as const;\n')
