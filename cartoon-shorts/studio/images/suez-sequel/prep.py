# prep.py - split the sheets, trim, normalise the guy's colours, measure anchors
# -> public/suez-sequel/*.png + canal.jpg + lake.jpg + src/suez-sequel/sprites.ts   (run from images/suez-sequel)
import json, os
import numpy as np, cv2
from PIL import Image, ImageDraw
OUT = '../../public/suez-sequel'
os.makedirs(OUT, exist_ok=True)
exec(open('prep_lib.py').read())
info = {}
def despill_mag(a):
    r, g, b = [a[..., i].astype(int) for i in range(3)]
    a[(r > g + 90) & (b > g + 90), 3] = 0
    return a
def save(name, a, guy=True, pad=12, mag=False):
    a = despill_mag(a) if mag else despill(a)
    a = drop_specks(a)
    if guy:
        a = normalise(a); a, nfix = fix_outline(a)
        if nfix: print('   outline fixed', name, nfix, 'px')
    a, off = trim(a, pad)
    Image.fromarray(a, 'RGBA').save(f'{OUT}/{name}.png', optimize=True)
    d = dict(w=a.shape[1], h=a.shape[0], feet=feet(a), **box(a))
    if guy: d['hd'] = head_disc(a)
    info[name] = d
    print(name, a.shape[1], a.shape[0], [round(v) for v in d['hd']] if guy else '')
    Image.fromarray(a, 'RGBA').save(f'qa/spr_{name}.png')
    return a
def extreme(a, fn):
    ys, xs = np.where(a[..., 3] > 128); i = np.argmax(fn(xs, ys)); return [int(xs[i]), int(ys[i])]
for n, s in zip(['cheer', 'point', 'shock'], split_n(load('guyA'), 3)): a = save(n, s)
info['point']['tip'] = extreme(np.asarray(Image.open(f'{OUT}/point.png')), lambda x, y: x)
for n, s in zip(['fish', 'nervous', 'refuse'], split_n(load('guyB'), 3)): a = save(n, s)
f = np.asarray(Image.open(f'{OUT}/fish.png')); info['fish']['rodtip'] = extreme(f, lambda x, y: x - y)
s = save('ship', load('ship'), guy=False, mag=True)
# waterline: bottom of the red stripe; deck line: top of the hull (navy) near the bow; bow tip
sh = s.astype(int)
navy = (np.abs(sh[..., :3] - np.array([43, 63, 92])).sum(2) < 60) & (sh[..., 3] > 200)
ys, xs = np.where(navy); info['ship']['hullTop'] = int(np.percentile(ys, 2)); info['ship']['bowX'] = int(xs.max())
red = (np.abs(sh[..., :3] - np.array([181, 71, 58])).sum(2) < 70) & (sh[..., 3] > 200)
ys, xs = np.where(red); info['ship']['keel'] = int(ys.max()); info['ship']['stripeTop'] = int(np.percentile(ys, 3))
print('ship', info['ship'])
for n, s in zip(['tug', 'digger', 'palm'], split_n(load('props'), 3)): save(n, s, guy=False, mag=True)
# plates: sky padded above, mirror-padded sideways
for n in ['canal', 'lake']:
    pl = np.asarray(Image.open(f'raw/{n}.png').convert('RGB')).copy(); H, W = pl.shape[:2]
    sky = pl[300:340, 200:400].reshape(-1, 3).mean(0).astype(np.uint8)
    ext = np.concatenate([np.tile(sky, (400, W, 1)), pl], 0)
    ext = cv2.copyMakeBorder(ext, 0, 0, 512, 512, cv2.BORDER_REFLECT_101)
    Image.fromarray(ext).save(f'{OUT}/{n}.jpg', quality=92)
    # water rows: blue-ish dominant rows
    blu = ((pl[..., 2].astype(int) - pl[..., 0].astype(int)) > 60).mean(1)
    rows = np.where(blu > 0.8)[0]
    info[n] = dict(w=int(ext.shape[1]), h=int(ext.shape[0]), padX=512, padTop=400, srcW=W, srcH=H, sky='#%02X%02X%02X' % tuple(sky))
    print(n, ext.shape, 'sky', info[n]['sky'], 'blue rows', rows.min() if len(rows) else None, rows.max() if len(rows) else None)
json.dump(info, open('sprites.json', 'w'), indent=1)
os.makedirs('../../src/suez-sequel', exist_ok=True)
with open('../../src/suez-sequel/sprites.ts', 'w') as f:
    f.write('// generated by images/suez-sequel/prep.py - native sizes and anchors (px of the trimmed sprite)\n')
    f.write('export const SPR = ' + json.dumps(info) + ' as const;\n')
