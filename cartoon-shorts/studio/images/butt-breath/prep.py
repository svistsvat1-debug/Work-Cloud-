# prep.py - split the sheets, trim, normalise the guy colours, measure anchors -> public/butt-breath + src/butt-breath/sprites.ts
import json, os
import numpy as np, cv2
from PIL import Image
OUT = '../../public/butt-breath'
os.makedirs(OUT, exist_ok=True)
exec(open('prep_lib.py').read())
info = {}
def despill_mag(a):
    r, g, b = [a[..., i].astype(int) for i in range(3)]
    a[(r > g + 90) & (b > g + 90), 3] = 0
    return a
def save(name, a, guy=True, pad=12, mag=False):
    a = despill_mag(a) if mag else despill(a)
    a = drop_specks(a)
    if guy:
        a = normalise(a); a, nfix = fix_outline(a)
        if nfix: print('   outline fixed', name, nfix, 'px')
    a, off = trim(a, pad)
    Image.fromarray(a, 'RGBA').save(f'{OUT}/{name}.png', optimize=True)
    d = dict(w=a.shape[1], h=a.shape[0], feet=feet(a), **box(a))
    if guy: d['hd'] = head_disc(a)
    info[name] = d
    print(name, a.shape[1], a.shape[0], [round(v) for v in d['hd']] if guy else '')
    Image.fromarray(a, 'RGBA').save(f'qa/spr_{name}.png')
    return a
for n, s in zip(['volunteer', 'hold', 'win'], split_n(load('guyA'), 3)): save(n, s)
for n, s in zip(['gulp', 'ache', 'run'], split_n(load('guyB'), 3)): save(n, s)
for n, s in zip(['docTalk', 'docShow', 'docClap'], split_n(load('doc'), 3)): save(n, s)
for n, s in zip(['pigSick', 'pigHappy', 'pigSmug'], split_n(load('pig'), 3)): save(n, s, guy=False)
for n, s in zip(['toilet', 'iv', 'watch'], split_n(load('props'), 3)): save(n, s, guy=False, mag=True)
# IV bag box: pale-blue liquid pixels
iv = np.asarray(Image.open(f'{OUT}/iv.png')).astype(int)
liq = (np.abs(iv[..., :3] - np.array([191, 230, 245])).sum(2) < 60) | (np.abs(iv[..., :3] - np.array([156, 211, 234])).sum(2) < 60)
liq &= iv[..., 3] > 200
ys, xs = np.where(liq); info['iv']['bag'] = [int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max())]
# stopwatch face: white pixels
wt = np.asarray(Image.open(f'{OUT}/watch.png')).astype(int)
wh = (wt[..., :3].sum(2) > 740) & (wt[..., 3] > 200); ys, xs = np.where(wh)
info['watch']['face'] = [int(np.median(xs)), int(np.percentile(ys, 50)), int((xs.max() - xs.min()) / 2)]
print('iv bag', info['iv']['bag'], 'watch face', info['watch']['face'])
pl = Image.open('raw/clinic.png').convert('RGB'); pl.save(f'{OUT}/clinic.jpg', quality=92)
info['clinic'] = dict(w=pl.width, h=pl.height)
json.dump(info, open('sprites.json', 'w'), indent=1)
with open('../../src/butt-breath/sprites.ts', 'w') as f:
    f.write('// generated by images/butt-breath/prep.py - native sizes and anchors (px of the trimmed sprite)\n')
    f.write('export const SPR = ' + json.dumps(info) + ' as const;\n')
