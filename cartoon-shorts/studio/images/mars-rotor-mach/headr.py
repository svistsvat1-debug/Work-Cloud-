# headr.py - pigeon head radius per sprite: largest inscribed disc of the dark slate head (+eye) region near the eye
import json, numpy as np, cv2
from PIL import Image
info = json.load(open('sprites.json'))
HEAD = np.array([0x64, 0x6C, 0x79], float)
for n in [k for k in info if k.startswith('p_')]:
    a = np.asarray(Image.open(f'qa/spr_{n}.png').convert('RGBA')).astype(float)
    rgb, al = a[..., :3], a[..., 3]
    head = (np.sqrt(((rgb - HEAD) ** 2).sum(2)) < 34) & (al > 200)
    white = (rgb.min(2) > 200) & (al > 200)
    dark = (rgb.sum(2) < 150) & (al > 200)
    m = (head | white | dark).astype(np.uint8)
    m = cv2.morphologyEx(m, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))
    ex, ey = info[n]['eyes'][0][:2]
    n_, lab = cv2.connectedComponents(m)
    l = lab[int(ey), int(ex)]
    comp = (lab == l).astype(np.uint8)
    dt = cv2.distanceTransform(comp, cv2.DIST_L2, 5)
    y, x = np.unravel_index(dt.argmax(), dt.shape)
    info[n]['head'] = [float(x), float(y), float(dt.max())]
    print(n, 'head', int(x), int(y), round(float(dt.max()), 1), 'eye', int(ex), int(ey))
json.dump(info, open('sprites.json', 'w'), indent=1)
with open('../../src/pigeon-landing/sprites.ts', 'w') as f:
    f.write('// generated by images/pigeon-landing/prep.py + headr.py - native sizes and anchors (px of the trimmed sprite)\n')
    f.write('export const SPR = ' + json.dumps(info) + ' as const;\n')
