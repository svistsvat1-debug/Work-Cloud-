# prep.py - split sheets, trim, normalise the guy, measure anchors -> public/mars-rotor-mach + src/mars-rotor-mach/sprites.ts
import json, os
import numpy as np, cv2
from PIL import Image, ImageDraw
OUT = '../../public/mars-rotor-mach'
os.makedirs(OUT, exist_ok=True); os.makedirs('qa', exist_ok=True)
exec(open('prep_lib.py').read())
info = {}

def save(name, a, guy=True, pad=12):
    a = despill(a); a = drop_specks(a)
    if guy:
        a = normalise(a); a, nfix = fix_outline(a)
    a, off = trim(a, pad)
    Image.fromarray(a, 'RGBA').save(f'{OUT}/{name}.png', optimize=True)
    d = dict(w=a.shape[1], h=a.shape[0], feet=feet(a), **box(a))
    if guy: d['hd'] = head_disc(a)
    info[name] = d
    Image.fromarray(a, 'RGBA').save(f'qa/spr_{name}.png')
    print(name, a.shape[1], a.shape[0], d.get('hd'))
    return a

def grid(name):
    a = Image.open(f'qa/spr_{name}.png'); w, h = a.size
    bg = Image.new('RGBA', (w, h), (215, 215, 215, 255)); bg.alpha_composite(a); d = ImageDraw.Draw(bg)
    for x in range(0, w, 50): d.line([(x, 0), (x, h)], fill=(255, 0, 0, 255) if x % 100 == 0 else (255, 170, 170, 255))
    for y in range(0, h, 50): d.line([(0, y), (w, y)], fill=(0, 0, 255, 255) if y % 100 == 0 else (170, 170, 255, 255))
    for x in range(0, w, 100): d.text((x + 2, 2), str(x), fill='red')
    for y in range(0, h, 100): d.text((2, y + 2), str(y), fill='blue')
    bg.convert('RGB').save(f'qa/measure_{name}.jpg', quality=85)

save('hero', load('hero'))
for n, s in zip(['shrug', 'pull', 'duck'], split_n(load('guyA'), 3)): save(n, s)
for n, s in zip(['peek', 'cheer', 'stunned'], split_n(load('guyB'), 3)): save(n, s)
h = save('heli', load('heli'), guy=False)
# mast: column through the middle; rotor zone between the body top and the panel bottom
al = h[..., 3] > 128
for n, s in zip(['tank', 'shield', 'sign'], split_n(load('objects'), 3)): save(n, s, guy=False)
for n in info: grid(n)

for p in ['mars', 'chamber']:
    pl = np.asarray(Image.open(f'raw/{p}.png').convert('RGB'))
    ext = cv2.copyMakeBorder(pl, 0, 0, 400, 400, cv2.BORDER_REFLECT_101)
    Image.fromarray(ext).save(f'{OUT}/{p}.jpg', quality=92)
    info[p] = dict(w=int(ext.shape[1]), h=int(ext.shape[0]), padX=400)

json.dump(info, open('sprites.json', 'w'), indent=1)
os.makedirs('../../src/mars-rotor-mach', exist_ok=True)
