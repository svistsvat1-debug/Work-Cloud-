# prep.py - split pair sheets, trim, normalise the guy's colours, measure heads / feet / anchors
# -> public/turkey-eggs/*.png + src/turkey-eggs/sprites.ts   (run from images/turkey-eggs; keyed/ = cut-outs, raw/ = plate)
import json, os
import numpy as np, cv2
from PIL import Image

OUT = '../../public/turkey-eggs'
os.makedirs(OUT, exist_ok=True)
PAL = np.array([[254, 253, 253], [237, 235, 235], [252, 141, 144]], float)  # channel palette (memory/STYLE.md)

def load(n): return np.asarray(Image.open(f'keyed/{n}.png').convert('RGBA')).copy()

def trim(a, pad=12):
    ys, xs = np.where(a[..., 3] > 10)
    y0, y1, x0, x1 = max(ys.min() - pad, 0), min(ys.max() + pad + 1, a.shape[0]), max(xs.min() - pad, 0), min(xs.max() + pad + 1, a.shape[1])
    return a[y0:y1, x0:x1].copy(), (int(x0), int(y0))

def normalise(a):
    rgb = a[..., :3].astype(float); op = a[..., 3] == 255
    D = np.stack([np.sqrt(((rgb - c) ** 2).sum(2)) for c in PAL])   # nearest palette colour wins
    k = D.argmin(0); dm = D.min(0)
    for i, c in enumerate(PAL):
        m = op & (dm < 40) & (k == i); rgb[m] = c
    d = np.sqrt((rgb ** 2).sum(2)); rgb[op & (d < 25)] = 0
    a[..., :3] = rgb.astype(np.uint8); return a

def feet(a):
    al = a[..., 3]; ys, xs = np.where(al > 128); yb = ys.max(); band = ys > yb - 0.035 * (yb - ys.min())
    return [float((xs[band].min() + xs[band].max()) / 2), int(yb)]

def head_disc(a, top=0.6, closeup=False):
    al = a[..., 3]; h, w = al.shape
    white = ((a[..., :3].astype(int).sum(2) > 600) & (al > 128)).astype(np.uint8)
    ff = white.copy(); cv2.floodFill(ff, np.zeros((h + 2, w + 2), np.uint8), (0, 0), 2)
    solid = np.where(ff == 2, 0, 1).astype(np.uint8)
    if not closeup: solid[int(h * top):] = 0
    dt = cv2.distanceTransform(solid, cv2.DIST_L2, 5)
    hy, hx = np.unravel_index(dt.argmax(), dt.shape)
    return [int(hx), int(hy), float(dt[hy, hx])]

def split(a, k):
    col = (a[..., 3] > 10).any(0); xs = np.where(col)[0]
    runs = []; s = xs[0]
    for i in range(1, len(xs)):
        if xs[i] > xs[i - 1] + 1: runs.append((s, xs[i - 1])); s = xs[i]
    runs.append((s, xs[-1])); runs = sorted(runs, key=lambda r: r[1] - r[0], reverse=True)[:k]; runs.sort()
    out = []
    for x0, x1 in runs:
        sub = a.copy(); sub[:, :max(x0 - 4, 0)] = 0; sub[:, x1 + 5:] = 0; out.append(sub)
    return out

info = {}
def save(name, a, guy=False, closeup=False, extra=None):
    if guy: a = normalise(a)
    a, off = trim(a)
    Image.fromarray(a, 'RGBA').save(f'{OUT}/{name}.png', optimize=True)
    d = dict(w=a.shape[1], h=a.shape[0], off=list(off), feet=feet(a))
    if guy: d['head'] = head_disc(a, closeup=closeup)
    if extra: d.update(extra(a))
    info[name] = d
    return a

def colour_box(a, test):
    rgb = a[..., :3].astype(int); m = test(rgb) & (a[..., 3] > 200)
    ys, xs = np.where(m)
    if len(xs) == 0: return None
    return [int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max())]

# the guy
blueface = lambda r: (r[..., 2] > r[..., 0] + 50) & (r[..., 2] > 170)
save('hero', load('hero'), guy=True)
save('yum', load('yum'), guy=True)
save('shrug', load('shrug'), guy=True)
save('shock', load('shock'), guy=True, closeup=True)
# turkeys: anchor = feet; face box = the bare light-blue face
save('turkey', load('turkey'), extra=lambda a: dict(face=colour_box(a, blueface)))
strain, peck = split(load('turkey2'), 2)
save('strain', strain, extra=lambda a: dict(face=colour_box(a, blueface)))
save('peck', peck, extra=lambda a: dict(face=colour_box(a, blueface)))
# chick pair: the shell bottom is cream; measure its box
cream = lambda r: (r[..., 0] > 225) & (r[..., 1] > 210) & (r[..., 2] > 180) & (r[..., 2] < 235)
happy, scared = split(load('chick'), 2)
save('chick', happy, extra=lambda a: dict(shell=colour_box(a, cream)))
save('chick_scared', scared, extra=lambda a: dict(shell=colour_box(a, cream)))
hen, hen_lay = split(load('chicken'), 2)
save('hen', hen)
save('hen_lay', hen_lay)
nest, grain = split(load('props'), 2)
save('nest', nest)
save('grain', grain)
save('roast', load('roast'))

# background plate: horizon = first row of the fence/grass under the sky in the middle column
bg = np.asarray(Image.open('raw/bg.png').convert('RGB')).astype(int)
col = bg[:, 400]
sky = (col[:, 2] > col[:, 0] + 25) & (col[:, 2] > 180)
nz = np.where(~sky)[0]; hz = int(nz[nz > 400].min())
g = (bg[:, :, 1] > bg[:, :, 0] + 40) & (bg[:, :, 1] > 150)
grass_top = int(np.where(g[:, 512])[0][np.where(g[:, 512])[0] > hz].min())
Image.fromarray(bg.astype(np.uint8)).save(f'{OUT}/bg.png', optimize=True)
info['bg'] = dict(w=bg.shape[1], h=bg.shape[0], horizon=hz, grassTop=grass_top, sky=list(map(int, bg[20, 500])), grass=list(map(int, bg[1500, 500])))
os.makedirs('../../src/turkey-eggs', exist_ok=True)
open('../../src/turkey-eggs/sprites.ts', 'w').write('// generated by images/turkey-eggs/prep.py\nexport const SPR = ' + json.dumps(info) + ' as const;\n')
