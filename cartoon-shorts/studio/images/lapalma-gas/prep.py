# prep.py - split the sheets, trim, normalise the guy's colours, measure anchors
# -> public/lapalma-gas/*.png + island.jpg + house.jpg + src/lapalma-gas/sprites.ts   (run from images/lapalma-gas)
import json, os, shutil
import numpy as np, cv2
from PIL import Image
OUT = '../../public/lapalma-gas'
os.makedirs(OUT, exist_ok=True)
exec(open('prep_lib.py').read())
info = {}
def despill_mag(a):
    r, g, b = [a[..., i].astype(int) for i in range(3)]
    a[(r > g + 90) & (b > g + 90), 3] = 0
    return a
def save(name, a, guy=True, pad=12, mag=False):
    a = despill_mag(a) if mag else despill(a)
    a = drop_specks(a)
    if guy:
        a = normalise(a); a, nfix = fix_outline(a)
        if nfix: print('   outline fixed', name, nfix, 'px')
    a, off = trim(a, pad)
    Image.fromarray(a, 'RGBA').save(f'{OUT}/{name}.png', optimize=True)
    d = dict(w=a.shape[1], h=a.shape[0], feet=feet(a), **box(a))
    if guy: d['hd'] = head_disc(a)
    info[name] = d
    print(name, a.shape[1], a.shape[0], [round(v) for v in d['hd']] if guy else '')
    Image.fromarray(a, 'RGBA').save(f'qa/spr_{name}.png')
    return a
for n, s in zip(['scared', 'relief', 'shrug'], split_n(load('guyA'), 3)): save(n, s)
for n, s in zip(['walk', 'stick', 'sit'], split_n(load('guyB'), 3)): save(n, s, mag=True)
save('close', load('guyC'))
for n, s in zip(['bird', 'cat', 'barrier'], split_n(load('props'), 3)): save(n, s, guy=False)
for n in ['island', 'house']:
    Image.open(f'raw/{n}.png').convert('RGB').save(f'{OUT}/{n}.jpg', quality=92)
    info[n] = dict(w=1024, h=1536)
json.dump(info, open('sprites.json', 'w'), indent=1)
os.makedirs('../../src/lapalma-gas', exist_ok=True)
with open('../../src/lapalma-gas/sprites.ts', 'w') as f:
    f.write('// generated by images/lapalma-gas/prep.py - native sizes and anchors (px of the trimmed sprite)\n')
    f.write('export const SPR = ' + json.dumps(info) + ' as const;\n')
