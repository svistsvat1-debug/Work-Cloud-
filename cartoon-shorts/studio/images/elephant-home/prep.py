# prep.py - split sheets, trim, normalise the guy colours, measure anchors -> public/elephant-home + src/elephant-home/sprites.ts
import json, os
import numpy as np, cv2
from PIL import Image
OUT = '../../public/elephant-home'
os.makedirs(OUT, exist_ok=True); os.makedirs('qa', exist_ok=True)
exec(open('prep_lib.py').read())
info = {}
def despill_mag(a):
    r, g, b = [a[..., i].astype(int) for i in range(3)]
    a[(r > g + 90) & (b > g + 90), 3] = 0
    return a
def save(name, a, guy=True, mag=False):
    a = despill_mag(a) if mag else despill(a)
    a = drop_specks(a)
    if guy:
        a = normalise(a); a, _ = fix_outline(a)
    a, off = trim(a, 12)
    Image.fromarray(a, 'RGBA').save(f'{OUT}/{name}.png', optimize=True)
    d = dict(w=a.shape[1], h=a.shape[0], feet=feet(a), **box(a))
    if guy: d['hd'] = head_disc(a)
    info[name] = d; print(name, d['w'], d['h'])
for n, s in zip(['binoc', 'shock', 'push'], split_n(load('guyA'), 3)): save(n, s)
for n, s in zip(['shrug', 'point', 'cheer'], split_n(load('guyB'), 3)): save(n, s)
for n, s in zip(['eWalk', 'eSleep', 'eHappy'], split_n(load('ele'), 3)): save(n, s, guy=False)
for n, s in zip(['truck', 'pine', 'corn'], split_n(load('props'), 3)): save(n, s, guy=False, mag=True)
for p in ['road', 'river']:
    pl = Image.open(f'raw/{p}.png').convert('RGB'); pl.save(f'{OUT}/{p}.jpg', quality=92); info[p] = dict(w=pl.width, h=pl.height)
json.dump(info, open('sprites.json', 'w'), indent=1)
with open('../../src/elephant-home/sprites.ts', 'w') as f:
    f.write('// generated by images/elephant-home/prep.py\nexport const SPR = ' + json.dumps(info) + ' as const;\n')
# QA sheet
names = [k for k in info if k not in ('road', 'river')]
W = 360; sheet = Image.new('RGB', (W * 6, W * 2 * 2), (255, 0, 255))
for i, n in enumerate(names):
    im = Image.open(f'{OUT}/{n}.png'); im.thumbnail((W - 10, W - 10))
    x, y = (i % 6) * W, (i // 6) * W
    bg = Image.new('RGB', (W, W), (255, 0, 255) if i % 2 else (20, 30, 90)); bg.paste(im, (5, 5), im); sheet.paste(bg, (x, y))
sheet.save('qa/sheet.png')
