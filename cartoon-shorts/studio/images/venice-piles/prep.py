# prep.py - split sheets, trim, normalise character colours, measure anchors
# -> public/venice-piles/*.png + src/venice-piles/sprites.ts   (run from images/venice-piles)
import json, os
import numpy as np, cv2
from PIL import Image

OUT = '../../public/venice-piles'
os.makedirs(OUT, exist_ok=True)
PAL = np.array([[254, 253, 253], [237, 235, 235], [252, 141, 144]], float)  # memory/STYLE.md

def load(n): return np.asarray(Image.open(f'keyed/{n}.png').convert('RGBA')).copy()

def trim(a, pad=12):
    ys, xs = np.where(a[..., 3] > 10)
    y0, y1, x0, x1 = max(ys.min() - pad, 0), min(ys.max() + pad + 1, a.shape[0]), max(xs.min() - pad, 0), min(xs.max() + pad + 1, a.shape[1])
    return a[y0:y1, x0:x1].copy(), (int(x0), int(y0))

def normalise(a):  # nearest palette colour wins (STYLE lesson)
    rgb = a[..., :3].astype(float); op = a[..., 3] == 255
    D = np.stack([np.sqrt(((rgb - c) ** 2).sum(2)) for c in PAL])
    k = D.argmin(0); dm = D.min(0)
    for i, c in enumerate(PAL):
        m = op & (dm < 40) & (k == i); rgb[m] = c
    d = np.sqrt((rgb ** 2).sum(2)); rgb[op & (d < 25)] = 0
    a[..., :3] = rgb.astype(np.uint8); return a

def feet(a):
    al = a[..., 3]; ys, xs = np.where(al > 128); yb = ys.max(); band = ys > yb - 0.035 * (yb - ys.min())
    return [float((xs[band].min() + xs[band].max()) / 2), int(yb)]

def head_disc(a):
    h, w = a.shape[:2]
    a8 = (a[..., 3] > 128).astype(np.uint8); ff = a8.copy()
    cv2.floodFill(ff, np.zeros((h + 2, w + 2), np.uint8), (0, 0), 2)
    solid = np.where(ff == 2, 0, 1).astype(np.uint8)
    dt = cv2.distanceTransform(solid, cv2.DIST_L2, 5)
    hy, hx = np.unravel_index(dt.argmax(), dt.shape)
    return [float(hx), float(hy), float(dt[hy, hx])]

def split(a, k):
    col = (a[..., 3] > 10).any(0); xs = np.where(col)[0]
    runs = []; s = xs[0]
    for i in range(1, len(xs)):
        if xs[i] > xs[i - 1] + 1: runs.append((s, xs[i - 1])); s = xs[i]
    runs.append((s, xs[-1])); runs = sorted(runs, key=lambda r: r[1] - r[0], reverse=True)[:k]; runs.sort()
    out = []
    for x0, x1 in runs:
        sub = a.copy(); sub[:, :max(x0 - 4, 0)] = 0; sub[:, x1 + 5:] = 0; out.append(sub)
    return out

def box(a):
    ys, xs = np.where(a[..., 3] > 128)
    return dict(left=int(xs.min()), right=int(xs.max()), top=int(ys.min()), bottom=int(ys.max()))

info = {}
def save(name, a, guy=False, extra=None, pad=12):
    if guy: a = normalise(a)
    a, off = trim(a, pad)
    Image.fromarray(a, 'RGBA').save(f'{OUT}/{name}.png', optimize=True)
    d = dict(w=a.shape[1], h=a.shape[0], off=list(off), feet=feet(a), **box(a))
    if guy: d['head'] = head_disc(a)
    if extra: d.update(extra(a))
    info[name] = d
    return a

def tip_extra(a):
    al = a[..., 3] > 128; ys, xs = np.where(al); xr = xs.max()
    return dict(tip=[int(xr), int(np.median(ys[xs >= xr - 3]))])
save('hero', load('hero'), guy=True, extra=tip_extra)
shock, thumb = split(load('guyA'), 2)
save('shock', shock, guy=True)
save('thumb', thumb, guy=True)
save('dig', load('dig'), guy=True)

def tower_extra(a):
    al = a[..., 3] > 128; rgb = a[..., :3].astype(int)
    # brick shaft rows: red-brown pixels
    br = (rgb[..., 0] > 130) & (rgb[..., 1] < 110) & (rgb[..., 2] < 90) & al
    ys = np.where(br.any(1))[0]
    return dict(shaftTop=int(ys.min()), shaftBottom=int(ys.max()))
save('tower', load('tower'), extra=tower_extra)

for i, p in enumerate(split(load('logs'), 5)):
    save(f'pole{i}', p)
mush, bell, rubble = split(load('props'), 3)
save('mush', mush); save('bell', bell); save('rubble', rubble)

bg = Image.open('raw/bg.png').convert('RGB')
bg.save(f'{OUT}/bg.png', optimize=True)
# horizon / pavement top: first row from the bottom whose mean colour is far from pavement
arr = np.asarray(bg).astype(int); pav = arr[-50:].reshape(-1, 3).mean(0)
rowd = np.sqrt(((arr.mean(1) - pav) ** 2).sum(1))
pt = int(np.where(rowd > 25)[0].max()) + 1
info['bg'] = dict(w=bg.width, h=bg.height, pave=pt)
os.makedirs('../../src/venice-piles', exist_ok=True)
open('../../src/venice-piles/sprites.ts', 'w').write('// generated by images/venice-piles/prep.py\nexport const SPR = ' + json.dumps(info) + ' as const;\n')
for k, v in info.items(): print(k, v)
