# prep.py - split pair sheets, trim, normalise colours, measure head/feet -> public/ocean-trench + src/ocean-trench/sprites.ts
import json, os
import numpy as np, cv2
from PIL import Image

OUT = '../../public/ocean-trench'
os.makedirs(OUT, exist_ok=True)
PAL = np.array([[254, 253, 253], [237, 235, 235], [252, 141, 144]], float)  # fill, shade, tongue (from the hero)

def load(n): return np.asarray(Image.open(f'keyed/{n}.png').convert('RGBA')).copy()

def split(a):
    al = a[..., 3]; h, w = al.shape
    empty = (al > 10).sum(0) == 0
    mid = w // 2; best = None
    # widest run of empty columns near the middle
    runs = []; x = 0
    while x < w:
        if empty[x]:
            s = x
            while x < w and empty[x]: x += 1
            runs.append((s, x))
        else: x += 1
    runs = [r for r in runs if r[0] > 0 and r[1] < w]
    s, e = max(runs, key=lambda r: r[1] - r[0])
    c = (s + e) // 2
    return a[:, :c], a[:, c:]

def trim(a, pad=12):
    ys, xs = np.where(a[..., 3] > 10)
    y0, y1, x0, x1 = max(ys.min() - pad, 0), min(ys.max() + pad + 1, a.shape[0]), max(xs.min() - pad, 0), min(xs.max() + pad + 1, a.shape[1])
    return a[y0:y1, x0:x1].copy()

def normalise(a):
    rgb = a[..., :3].astype(float); op = a[..., 3] == 255
    for c in PAL:
        d = np.sqrt(((rgb - c) ** 2).sum(2)); m = op & (d < 40); rgb[m] = c
    d = np.sqrt((rgb ** 2).sum(2)); rgb[op & (d < 25)] = 0
    a[..., :3] = rgb.astype(np.uint8); return a

def head_feet(a):
    al = a[..., 3]; h, w = al.shape
    white = ((a[..., :3].astype(int).sum(2) > 600) & (al > 128)).astype(np.uint8)
    ff = white.copy(); cv2.floodFill(ff, np.zeros((h + 2, w + 2), np.uint8), (0, 0), 2)
    solid = np.where(ff == 2, 0, 1).astype(np.uint8)
    dt = cv2.distanceTransform(solid, cv2.DIST_L2, 5)
    hy, hx = np.unravel_index(dt.argmax(), dt.shape)
    ys, xs = np.where(al > 128); yb = ys.max(); band = ys > yb - 0.035 * (yb - ys.min())
    return dict(head=[int(hx), int(hy), float(dt[hy, hx])], feet=[float(xs[band].mean()), int(yb)])

info = {}
def save(name, a, char=True):
    if char: a = normalise(a)
    a = trim(a)
    Image.fromarray(a, 'RGBA').save(f'{OUT}/{name}.png', optimize=True)
    d = dict(w=a.shape[1], h=a.shape[0])
    if char: d.update(head_feet(a))
    info[name] = d

for n in ['hero_hold', 'windup', 'throw_follow', 'smug_cu']: save(n, load(n))
L, R = split(load('pair_bored_sleep')); save('bored', L); save('sleep', R)
L, R = split(load('pair_catch')); save('alarm', L); save('deadpan_bag', R)
for n in ['volcano', 'bag', 'boat']: save(n, load(n), char=False)
b = np.asarray(Image.open('raw/bg_cutaway.png').convert('RGB'))
b = np.concatenate([b[:, :-3], np.repeat(b[:, -4:-3], 253, 1)], 1)  # extend the right edge by 250 px (plain bands) so the volcano fits
bg = Image.fromarray(b); bg.save(f'{OUT}/bg.png', optimize=True)
info['bg'] = dict(w=bg.width, h=bg.height)
os.makedirs('../../src/ocean-trench', exist_ok=True)
with open('../../src/ocean-trench/sprites.ts', 'w') as f:
    f.write('// generated by images/ocean-trench/prep.py\nexport const SPR = ' + json.dumps(info, indent=1) + ' as const;\n')
print(json.dumps(info, indent=1))
