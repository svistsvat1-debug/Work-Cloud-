# the magnifier lens centre: the pale-blue blob furthest right
def lens(a, rightmost=True):
    rgb = a[..., :3].astype(int); m = (a[..., 3] > 200) & (rgb[..., 2] > 200) & (rgb[..., 0] < 215) & (rgb[..., 0] > 150)
    n, lab, st, cen = cv2.connectedComponentsWithStats(m.astype(np.uint8), connectivity=8)
    blobs = [(st[i, cv2.CC_STAT_AREA], cen[i]) for i in range(1, n) if st[i, cv2.CC_STAT_AREA] > 300]
    blobs.sort(key=lambda b: -b[0])
    return [[float(c[0]), float(c[1]), float(np.sqrt(ar / np.pi))] for ar, c in blobs[:3]]
