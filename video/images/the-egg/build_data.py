"""Measure sprite anchors and pre-render the crowd rows for "The Egg".

Writes:
  src/egg/sprites.ts        sprite sizes + anchors (head circles, mug, feet, hands)
  public/the-egg/crowd/row_NN.png, halo_NN.png   one strip per crowd row (figures / halos), back rows lower-res
  src/egg/crowd.ts          row depth, world placement and pixel scale of every strip
usage: python3 build_data.py <video_root>
"""
import json, os, sys
import numpy as np
import cv2

ROOT = sys.argv[1]
SP = os.path.join(ROOT, "public/the-egg/sprites")
meta = json.load(open(os.path.join(SP, "sprites.json")))
rng = np.random.default_rng(11)


def load(name):
    return cv2.imread(os.path.join(SP, name + ".png"), cv2.IMREAD_UNCHANGED)


def alpha_box(a, thr=128):
    ys, xs = np.where(a > thr)
    return int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max())


def solid(a):
    a8 = (a > 128).astype(np.uint8); h, w = a8.shape; ff = a8.copy()
    cv2.floodFill(ff, np.zeros((h + 2, w + 2), np.uint8), (0, 0), 2)
    return np.where(ff == 2, 0, 1).astype(np.uint8)


def disc(a, region):
    s = solid(a); x0, y0, x1, y1 = region
    dt = cv2.distanceTransform(s, cv2.DIST_L2, 5)
    sub = dt[y0:y1, x0:x1]; y, x = np.unravel_index(sub.argmax(), sub.shape)
    return [float(x + x0), float(y + y0), float(sub[y, x])]


out = {}
for name, m in meta.items():
    im = load(name); a = im[..., 3]; h, w = a.shape
    box = alpha_box(a)
    head = m["head"]
    if name == "god":
        head = disc(a, (0, 0, w, int(h * 0.30)))
    if name == "hero_curled":
        head = disc(a, (int(w * 0.3), 0, w, int(h * 0.45)))
    out[name] = {"src": f"the-egg/sprites/{name}.png", "w": w, "h": h, "head": [round(v, 1) for v in head],
                 "box": list(box)}

# mug drawn in hero_float: largest red component
im = load("hero_float"); b, g, r, a = [im[..., i].astype(int) for i in range(4)]
red = ((r > 150) & (g < 110) & (b < 110) & (a > 200)).astype(np.uint8)
n, lab, st, cen = cv2.connectedComponentsWithStats(red, 8)
k = 1 + int(np.argmax(st[1:, cv2.CC_STAT_AREA]))
x, y, ww, hh = st[k, :4]
out["hero_float"]["mug"] = [float(x + ww / 2), float(y + hh / 2), float(ww), float(hh)]
im = load("mug"); b, g, r, a = [im[..., i].astype(int) for i in range(4)]
red = ((r > 150) & (g < 110) & (b < 110) & (a > 200)).astype(np.uint8)
n, lab, st, cen = cv2.connectedComponentsWithStats(red, 8)
k = 1 + int(np.argmax(st[1:, cv2.CC_STAT_AREA]))
x, y, ww, hh = st[k, :4]
out["mug"]["body"] = [float(x + ww / 2), float(y + hh / 2), float(ww), float(hh)]

os.makedirs(os.path.join(ROOT, "src/egg"), exist_ok=True)
with open(os.path.join(ROOT, "src/egg/sprites.ts"), "w") as f:
    f.write("// generated by images/the-egg/build_data.py - sprite sizes (px) and anchors in sprite pixels\n")
    f.write("export type SpriteInfo = {src: string; w: number; h: number; head: number[]; box: number[];"
            " mug?: number[]; body?: number[]};\n")
    f.write("export const SPR: Record<string, SpriteInfo> = " + json.dumps(out, indent=1) + ";\n")

# ---------------- crowd rows ----------------
CROWD = [n for n in meta if n.startswith("crowd_")]
HEAD_R_WORLD = 52.0
SC = HEAD_R_WORLD / 167.0          # one scale for the whole sheet (same drawing)
GROUND_Y = 1500.0
TOP_SPACE = 400.0                  # world units above the ground line kept in a strip (figure + halo)
BOTTOM_SPACE = 20.0
SPACING = 132.0
ROWS = [(1000.0 + i * 230.0) for i in range(32)]   # depths
CAM_Z_NEAR, CAM_Z_FAR = 300.0, -2100.0
cdir = os.path.join(ROOT, "public/the-egg/crowd"); os.makedirs(cdir, exist_ok=True)
sprites = {n: load(n) for n in CROWD}
feet = {n: alpha_box(sprites[n][..., 3])[3] for n in CROWD}
tops = {n: alpha_box(sprites[n][..., 3])[1] for n in CROWD}
rows_meta = []
for i, Z in enumerate(ROWS):
    kmax = 1000.0 / (Z - CAM_Z_NEAR)
    kmin = 1000.0 / (Z - CAM_Z_FAR)
    s = min(2.3, max(0.16, kmax * 2.2))          # strip px per world unit (4K = 2 px per screen px)
    half = 560.0 / kmin + 300.0
    W = 2 * half
    x_left = 540.0 - half
    Hw = TOP_SPACE + BOTTOM_SPACE
    pw, ph = int(W * s), int(Hw * s)
    row = np.zeros((ph, pw, 4), np.float32)
    halo = np.zeros((ph, pw, 4), np.float32)
    nfig = int(W / SPACING)
    off = rng.uniform(0, SPACING)
    last = None
    cache = {}
    for j in range(nfig):
        name = rng.choice(CROWD)
        while name == last:
            name = rng.choice(CROWD)
        last = name
        sj = SC * rng.uniform(0.94, 1.06)
        key = (name, round(sj, 3))
        spr = sprites[name]
        tw, th = max(1, int(spr.shape[1] * sj * s)), max(1, int(spr.shape[0] * sj * s))
        if key not in cache:
            cache[key] = cv2.resize(spr, (tw, th), interpolation=cv2.INTER_AREA).astype(np.float32) / 255.0
        im = cache[key]
        cx = off + j * SPACING + rng.uniform(-22, 22)          # world, relative to x_left
        gy = TOP_SPACE + rng.uniform(-8, 8)                     # ground line inside the strip (world)
        hx = meta[name]["head"][0]
        px0 = int((cx - hx * sj) * s)
        py0 = int((gy - feet[name] * sj) * s)
        x0, y0 = max(px0, 0), max(py0, 0)
        x1, y1 = min(px0 + im.shape[1], pw), min(py0 + im.shape[0], ph)
        if x1 <= x0 or y1 <= y0:
            continue
        src = im[y0 - py0:y1 - py0, x0 - px0:x1 - px0]
        a = src[..., 3:4]
        dst = row[y0:y1, x0:x1]
        dst[..., :3] = src[..., :3] * a + dst[..., :3] * (1 - a)
        dst[..., 3:4] = a + dst[..., 3:4] * (1 - a)
        # halo above the figure top
        top_w = gy - (feet[name] - tops[name]) * sj               # world y of the figure's top in the strip
        hcx, hcy = cx * s, (top_w - 26) * s
        rx, ry = 44 * s * sj / SC, 12 * s * sj / SC
        t_out = max(1, int(round(7 * s)))
        hl = np.zeros((ph, pw), np.uint8)
        ring = halo[..., :3]
        cv2.ellipse(halo, (int(hcx), int(hcy)), (int(rx), int(ry)), 0, 0, 360, (0.07, 0.07, 0.07, 1.0), -1, cv2.LINE_AA)
        cv2.ellipse(halo, (int(hcx), int(hcy)), (max(1, int(rx - t_out)), max(1, int(ry - t_out * 0.8))), 0, 0, 360,
                    (0.35, 0.82, 0.97, 1.0), -1, cv2.LINE_AA)   # golden fill (BGR)
        cv2.ellipse(halo, (int(hcx), int(hcy)), (max(1, int(rx * 0.58)), max(1, int(ry * 0.42))), 0, 0, 360,
                    (0.07, 0.07, 0.07, 1.0), -1, cv2.LINE_AA)
        inner = (max(1, int(rx * 0.58 - t_out * 0.9)), max(1, int(ry * 0.42 - t_out * 0.6)))
        cv2.ellipse(halo, (int(hcx), int(hcy)), inner, 0, 0, 360, (0, 0, 0, 0), -1, cv2.LINE_AA)
    cv2.imwrite(os.path.join(cdir, f"row_{i:02d}.png"), (np.clip(row, 0, 1) * 255).round().astype(np.uint8))
    cv2.imwrite(os.path.join(cdir, f"halo_{i:02d}.png"), (np.clip(halo, 0, 1) * 255).round().astype(np.uint8))
    rows_meta.append({"z": Z, "x": round(x_left, 1), "y": GROUND_Y - TOP_SPACE, "w": round(W, 1), "h": Hw,
                      "pw": pw, "ph": ph, "row": f"the-egg/crowd/row_{i:02d}.png",
                      "halo": f"the-egg/crowd/halo_{i:02d}.png"})
    print(f"row {i:02d} Z={Z:6.0f} strip {pw}x{ph} figs {nfig}")

with open(os.path.join(ROOT, "src/egg/crowd.ts"), "w") as f:
    f.write("// generated by images/the-egg/build_data.py - crowd strips: world box (x, y, w, h) at depth z\n")
    f.write("export const GROUND_Y = %.1f;\n" % GROUND_Y)
    f.write("export const CROWD_SCALE = %.5f;\n" % SC)
    f.write("export const ROWS = " + json.dumps(rows_meta, indent=1) + ";\n")
