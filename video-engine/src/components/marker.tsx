import React, {createContext, useContext, useId, useMemo} from 'react';
import {staticFile, useCurrentFrame} from 'remotion';
import {bbox, hatch, poly, Pt, seedOf} from '../lib/sketch';
import {prog} from '../lib/timing';

// Effective scale of the current drawing group, so ink width and marker texture stay similar on screen
// whether an object is drawn big or small.
export const ScaleCtx = createContext(1);
export const useScale = () => useContext(ScaleCtx);
export const Scaled: React.FC<{s: number; children: React.ReactNode}> = ({s, children}) => {
  const parent = useContext(ScaleCtx);
  return <ScaleCtx.Provider value={parent * Math.abs(s || 1)}>{children}</ScaleCtx.Provider>;
};

// Marker texture tiles generated by tools/textures.py (public/tex/<name>.jpg and <name>_d.jpg)
const TEX: Record<string, string> = {
  olive: '#6B7B3A', khaki: '#C2B280', steel: '#6E7B85', brown: '#8B5A2B', mud: '#7A5C3E', red: '#E8322B', orange: '#F58A1F',
  yellow: '#FFC93C', blue: '#1E88E5', green: '#3BA55C', grey: '#A7AEB2', white: '#F4F1EA', paper: '#F1E7CF',
  skinLight: '#F3D2B3', skinMid: '#C98E62', skinDark: '#7B4B2A', land: '#D9CC9A', sea: '#3A8FD8', ink: '#2A2A2A',
  darkolive: '#4E5A2A', hay: '#E3C35A', horse: '#8A6A4A', wood: '#A0703C', film: '#3C4650', skyblue: '#BFE3F5',
  brick: '#C46A4A', potato: '#C9A26B', tankdark: '#4A4A3A', moon: '#E9E4C8', bottle: '#F6E6A6', darkbrown: '#5B4636',
  hole: '#3E2C1E', fieldgrey: '#7C8471', darkkhaki: '#9C8B5E',
};
const ALIAS: Record<string, string> = {'#FFFFFF': 'white', '#1A1A1A': 'ink', '#EFE5CC': 'land', '#7FC4F0': 'skyblue', '#E4E7E9': 'white', '#F1EAD8': 'land'};
const rgb = (h: string) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const cache: Record<string, string> = {};
export const texFor = (hex: string): string => {
  const H = hex.toUpperCase();
  if (cache[H]) return cache[H];
  if (ALIAS[H]) return (cache[H] = ALIAS[H]);
  for (const [k, v] of Object.entries(TEX)) if (v.toUpperCase() === H) return (cache[H] = k);
  const c = rgb(H);
  let best = 'grey';
  let bd = Infinity;
  for (const [k, v] of Object.entries(TEX)) {
    const t = rgb(v);
    const d = (t[0] - c[0]) ** 2 * 0.3 + (t[1] - c[1]) ** 2 * 0.59 + (t[2] - c[2]) ** 2 * 0.11;
    if (d < bd) {
      bd = d;
      best = k;
    }
  }
  return (cache[H] = best);
};

const shiftPts = (pts: Pt[], dx: number, dy: number): Pt[] => pts.map(([x, y]) => [x + dx, y + dy]);

// Marker colouring: dark tile over the whole shape, lighter tile over the shape shifted up-left
// (leaves an automatic shade band along the bottom-right edge); colour appears with a scribble brush mask.
export const MarkerFill: React.FC<{pts: Pt[]; color: string; at: number; dur?: number; shade?: number; seed?: number; opacity?: number}> = ({
  pts,
  color,
  at,
  dur = 14,
  shade,
  seed,
  opacity = 1,
}) => {
  const f = useCurrentFrame();
  const sc = useScale();
  const id = useId().replace(/:/g, '');
  const b = useMemo(() => bbox(pts), [pts]);
  const size = Math.min(b.x1 - b.x0, b.y1 - b.y0);
  const sh = shade ?? Math.max(2.5, Math.min(16, size * 0.12));
  const clip = useMemo(() => poly(pts), [pts]);
  const inner = useMemo(() => poly(shiftPts(pts, -sh, -sh * 0.9)), [pts, sh]);
  const gap = 30 / Math.max(0.3, sc);
  const scribble = useMemo(() => hatch(b, gap, -35, seed ?? seedOf(pts.length, b.x0, b.y0)), [b, gap, seed, pts.length]);
  const p = prog(f, at, dur);
  if (p <= 0) return null;
  const name = texFor(color);
  const k = 0.7 / Math.max(0.2, sc);
  const W = b.x1 - b.x0 + 4;
  const Hh = b.y1 - b.y0 + 4;
  return (
    <g opacity={opacity}>
      <defs>
        <pattern id={`pb${id}`} patternUnits="userSpaceOnUse" width={512} height={512} patternTransform={`scale(${k})`}>
          <image href={staticFile(`tex/${name}.jpg`)} width={512} height={512} />
        </pattern>
        <pattern id={`pd${id}`} patternUnits="userSpaceOnUse" width={512} height={512} patternTransform={`scale(${k})`}>
          <image href={staticFile(`tex/${name}_d.jpg`)} width={512} height={512} />
        </pattern>
        <clipPath id={`ca${id}`}>
          <path d={clip} />
        </clipPath>
        <clipPath id={`cb${id}`}>
          <path d={inner} />
        </clipPath>
        {p < 1 ? (
          <mask id={`m${id}`} maskUnits="userSpaceOnUse" x={b.x0 - 40} y={b.y0 - 40} width={W + 80} height={Hh + 80}>
            <path d={scribble} pathLength={1} fill="none" stroke="#fff" strokeWidth={gap * 1.55} strokeLinecap="round" strokeLinejoin="round" strokeDasharray="1 1" strokeDashoffset={1 - p} />
          </mask>
        ) : null}
      </defs>
      <g clipPath={`url(#ca${id})`} mask={p < 1 ? `url(#m${id})` : undefined}>
        <rect x={b.x0 - 2} y={b.y0 - 2} width={W} height={Hh} fill={`url(#pd${id})`} />
        <g clipPath={`url(#cb${id})`}>
          <rect x={b.x0 - 2} y={b.y0 - 2} width={W} height={Hh} fill={`url(#pb${id})`} />
        </g>
      </g>
    </g>
  );
};
